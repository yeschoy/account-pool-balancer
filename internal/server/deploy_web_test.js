const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const source = fs.readFileSync(path.join(__dirname, 'web/app.js'), 'utf8');
const html = fs.readFileSync(path.join(__dirname, 'web/index.html'), 'utf8');
const registrationSource = fs.readFileSync(path.join(__dirname, 'web/deploy.js'), 'utf8');
// Classic scripts share a global lexical scope; per-file syntax checks miss collisions.
new vm.Script(source + '\n' + registrationSource);
assert.equal([...html.matchAll(/data-pool="deploy" role="tab"/g)].length, 1);
const context = { console, Date, localStorage: { getItem() { return 'deploy'; } } };
vm.createContext(context);
vm.runInContext(source.slice(source.indexOf('const POOLS ='), source.indexOf('// navigator.clipboard')), context);
vm.runInContext(source.slice(source.indexOf('function deployQuotaHTML('), source.indexOf('const effLimit =')), context);
assert.equal(vm.runInContext('managedKeyPool() && keyNeedsProvider()', context), true);
assert.equal(vm.runInContext('defaultGroup()', context), 'deploy');
assert.match(html, /data-pool="deploy" role="tab">Deploy 号池/);
assert.match(html, /id="deploy-settings"/);
assert.match(html, /id="shared-log-note"/);
let rendered = context.deployQuotaHTML({ deploy: { quotaState: 'not-connected', quotaReason: '<img onerror=bad>', catalogState: 'ok', catalogFresh: true, models: 2 } });
assert.match(rendered, /余额未知/);
assert.match(rendered, /&lt;img onerror=bad&gt;/);
assert.doesNotMatch(rendered, /<img|\$0\.00|额度已刷新/);
assert.match(rendered, /不是 Key 激活或推理授权证明/);
rendered = context.deployQuotaHTML({ deploy: { catalogState: 'failed', catalogError: '<script>bad</script>' } });
assert.match(rendered, /目录读取失败/);
assert.match(rendered, /&lt;script&gt;/);
vm.runInContext(source.slice(source.indexOf('async function accountAction('), source.indexOf('function accountForm(')), context);
(async () => {
  const calls = [], toasts = [];
  context.api = async (...args) => { calls.push(args); return { ok: true, quotaRefreshed: false, message: '模型目录已刷新；余额仍未知' }; };
  vm.runInContext(registrationSource.slice(registrationSource.indexOf('async function drApi('), registrationSource.indexOf('const DR_STATUS_LABEL =')), context);
  await context.drApi('/settings', { method: 'PUT', body: JSON.stringify({ max_retries: 3 }) });
  assert.equal(calls[0][0], 'PUT');
  assert.equal(calls[0][1], '/api/deploy/settings');
  assert.equal(calls[0][2].max_retries, 3);
  await context.drApi('/candidates');
  assert.deepEqual(calls[1], ['GET', '/api/deploy/candidates', undefined]);
  calls.length = 0;
  context.toast = (...args) => toasts.push(args);
  context.loadAccounts = async () => {};
  await context.accountAction({ id: 'd', provider: 'deploy' }, 'refresh');
  assert.deepEqual(calls, [['POST', '/api/accounts/d/refresh-quota']]);
  assert.deepEqual(toasts, [['模型目录已刷新；余额仍未知', undefined]]);
  context.api = async () => { throw new Error('目录检测失败'); };
  await context.accountAction({ id: 'd', provider: 'deploy' }, 'refresh');
  assert.deepEqual(toasts.at(-1), ['目录检测失败', 'error']);
  // 重发验证：只有"已注册、未验证、无会话、不在跑"的行才出现按钮
  assert.match(registrationSource, /data-dr-resend=\"/);
  assert.match(registrationSource, /resend-verification/);
  assert.match(source, /if \(isDeploy\(\)\) body\.deploy =/);
  assert.match(source, /el\.disabled = isDeploy\(\)/);
  console.log('Deploy web tests passed');
})().catch(error => { console.error(error); process.exitCode = 1; });
