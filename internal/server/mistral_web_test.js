const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const source = fs.readFileSync(path.join(__dirname, 'web/app.js'), 'utf8');
const html = fs.readFileSync(path.join(__dirname, 'web/index.html'), 'utf8');
const nodes = new Map();
function node(selector) {
  if (!nodes.has(selector)) nodes.set(selector, { value: '', checked: true, classList: { toggle() {} } });
  return nodes.get(selector);
}
const copied = [];
const context = { $: node, copyText: (v) => copied.push(v), toast() {}, localStorage: { getItem() { return 'mistral'; } }, document: {}, console };
vm.createContext(context);
const start = source.indexOf('const POOLS =');
const end = source.indexOf('const num =');
vm.runInContext(source.slice(start, end) + '\nglobalThis.poolNames=POOLS; Object.assign(globalThis, {defaultGroup, managedKeyPool});', context);
vm.runInContext(source.slice(source.indexOf('function accountForm('), source.indexOf('let editingAccountId')), context);
vm.runInContext('let accountsCache = [];\n' + source.slice(source.indexOf('function accountCredentialHTML('), source.indexOf('function accountRow(')), context);
vm.runInContext(source.slice(source.indexOf('const STRATEGY_HINTS'), source.indexOf('const QUOTA_FIELDS')) + '\nglobalThis.routingFields=routingFields;', context);
assert.ok(context.poolNames.includes('mistral'));
assert.equal(context.defaultGroup(), 'mistral');
assert.equal(context.managedKeyPool(), true);
const form = context.accountForm(null);
assert.match(form, /Mistral/);
assert.match(form, /pi/);
assert.doesNotMatch(form, /id="f-ctrl"/);
const account = { id: 'm1', name: '<img onerror=bad>', runtimeKey: 'mstrl_full_example_key', proxyUrl: 'http://user:p<a>ss@127.0.0.1:9', hasProxy: true };
const edit = context.accountForm(account);
assert.doesNotMatch(edit, /<img onerror/);
assert.match(edit, /value="mstrl_full_example_key"/);
assert.match(edit, /data-copy="runtimeKey"/);
assert.match(edit, /data-copy="proxyUrl"/);
assert.match(edit, /user:p&lt;a&gt;ss@/);
const display = context.accountCredentialHTML(account);
assert.match(display, /mstrl_full_example_key/);
assert.match(display, /data-account-copy="proxyUrl"/);
assert.doesNotMatch(display, /p<a>/);
context.account = account;
vm.runInContext('accountsCache = [account]; copyAccountField("m1", "runtimeKey"); copyAccountField("m1", "proxyUrl");', context);
assert.deepEqual(copied, [account.runtimeKey, account.proxyUrl]);
vm.runInContext('pool = "tokenharbor"', context);
assert.doesNotMatch(context.accountForm(account), /type="password"/);
vm.runInContext('pool = "mistral"', context);
for (const id of ['#f-conc','#f-rpm','#f-weight','#f-prio']) node(id).value='1';
node('#f-rt').value='opaque-example-key';
const payload = context.readAccountForm();
assert.equal(payload.provider, 'mistral');
assert.equal(payload.runtimeKey, 'opaque-example-key');
assert.equal(payload.enabled, true);
const fields = Array.from(context.routingFields(), f => f[0]);
for (const field of ['strategy','sticky','onBindingBusy','sessionHeaders','maxAccountsPerRequest','ignoreCatalog']) assert.ok(fields.includes(field));
assert.ok(!fields.includes('walletFallback'));
assert.match(html, /data-pool="mistral" role="tab">Mistral 号池/);
assert.match(html, /id="mistral-settings"/);
assert.match(html, /id="mistral-base"/);
assert.match(source, /body\.mistral = \{ baseUrl:/);
vm.runInContext(source.slice(source.indexOf('async function testAccount('), source.indexOf('// ---- device authorization ----')), context);
(async () => {
  let dialog;
  const requests = [];
  context.modal = async (options) => { dialog = options; };
  context.api = async (...args) => { requests.push(args); return { ok: true }; };
  await context.testAccount({ id: 'm1', name: 'Mistral test', provider: 'mistral' });
  assert.match(dialog.body, /默认 deepseek-v4-1-flash-1017/);
  assert.match(dialog.body, /只读取模型列表（余额未知）/);
  assert.equal(requests.length, 0);
  node('#test-model').value = '';
  await dialog.buttons.find((b) => b.value === 'inf').action();
  assert.equal(requests[0][1], '/api/accounts/m1/test');
  assert.equal(requests[0][2].inference, true);
  assert.equal(requests[0][2].model, ''); // the backend supplies the Mistral default
  node('#test-model').value = ' custom-mistral-model ';
  await dialog.buttons.find((b) => b.value === 'inf').action();
  assert.equal(requests[1][2].model, 'custom-mistral-model');
  await dialog.buttons.find((b) => b.value === 'free').action();
  assert.equal(requests[2][2].inference, false);
  await context.testAccount({ id: 't1', name: 'Token Harbor test', provider: 'tokenharbor' });
  assert.match(dialog.body, /该账号模型列表中的首个模型/);
  assert.doesNotMatch(dialog.body, /deepseek-v4-1-flash-1017/);
  console.log('Mistral web tests passed');
})().catch((error) => { console.error(error); process.exitCode = 1; });
