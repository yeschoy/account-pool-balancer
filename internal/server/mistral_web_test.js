const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const source = fs.readFileSync(path.join(__dirname, 'web/app.js'), 'utf8');
const html = fs.readFileSync(path.join(__dirname, 'web/index.html'), 'utf8');
const nodes = new Map();
function node(selector) {
  if (!nodes.has(selector)) nodes.set(selector, { value: '', checked: true, classList: { toggle() {} } });
  return nodes.get(selector);
}
const context = { $: node, localStorage: { getItem() { return 'mistral'; } }, document: {}, console };
vm.createContext(context);
const start = source.indexOf('const POOLS =');
const end = source.indexOf('const num =');
vm.runInContext(source.slice(start, end) + '\nglobalThis.poolNames=POOLS; Object.assign(globalThis, {defaultGroup, managedKeyPool});', context);
vm.runInContext(source.slice(source.indexOf('function accountForm('), source.indexOf('let editingAccountId')), context);
vm.runInContext(source.slice(source.indexOf('const STRATEGY_HINTS'), source.indexOf('const QUOTA_FIELDS')) + '\nglobalThis.routingFields=routingFields;', context);
assert.ok(context.poolNames.includes('mistral'));
assert.equal(context.defaultGroup(), 'mistral');
assert.equal(context.managedKeyPool(), true);
const form = context.accountForm(null);
assert.match(form, /Mistral/);
assert.match(form, /pi/);
assert.doesNotMatch(form, /id="f-ctrl"/);
const edit = context.accountForm({ name: '<img onerror=bad>', runtimeKey: 'mstrl_…1234', hasProxy: false });
assert.doesNotMatch(edit, /<img onerror/);
assert.doesNotMatch(edit, /data-copy="runtimeKey"/);
for (const id of ['#f-conc','#f-rpm','#f-weight','#f-prio']) node(id).value='1';
node('#f-rt').value='opaque-example-key';
const payload = context.readAccountForm();
assert.equal(payload.provider, 'mistral');
assert.equal(payload.runtimeKey, 'opaque-example-key');
assert.equal(payload.enabled, true);
const fields = Array.from(context.routingFields(), f => f[0]);
for (const field of ['strategy','sticky','onBindingBusy','sessionHeaders','maxAccountsPerRequest','ignoreCatalog']) assert.ok(fields.includes(field));
assert.ok(!fields.includes('walletFallback'));
assert.match(html, /data-pool="mistral" role="tab">Mistral 号池/);
assert.match(html, /id="mistral-settings"/);
assert.match(html, /id="mistral-base"/);
assert.match(source, /body\.mistral = \{ baseUrl:/);
console.log('Mistral web tests passed');
